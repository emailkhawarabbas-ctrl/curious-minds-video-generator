"""Check every SVG in the asset library for the whiteboard (stroke-by-stroke) look.

    PYTHONPATH=. python scripts/audit_assets.py [--out docs/ASSET_AUDIT.md]

For each asset it reports whether it is line art (every shape has an ink stroke), mixed, or
fill-only, how many fill-only shapes get an automatic traced outline (src/lively/drawing.py
``outline_asset``), and how much of the coloured area ends up with a drawn line around it.
Assets with low line coverage still pop their colour in without lines and should be redrawn.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import src  # noqa: F401,E402
from src.animation.asset_manager import get_asset_manager  # noqa: E402
from src.lively.drawing import classify_asset, stroke_order, outline_asset  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "docs" / "ASSET_AUDIT.md"))
    a = ap.parse_args()
    am = get_asset_manager()
    rows = []
    for aid in sorted(am.ids()):
        asset = am.get(aid)
        info = classify_asset(asset)
        info["strokes"] = len(stroke_order(outline_asset(asset)))
        info["id"] = aid
        rows.append(info)
    kinds = {k: [r for r in rows if r["kind"] == k] for k in ("line_art", "mixed", "fill_only")}
    redraw = [r for r in rows if r["needs_redraw"]]
    lines = ["# Asset audit: whiteboard drawing", "",
             "Generated by `scripts/audit_assets.py`. The whiteboard look traces every SVG stroke by stroke, "
             "then fades its colours in. Shapes that only have a fill (no ink outline) get an automatic outline "
             "traced around them, unless they are shines/shadows (light or translucent) or tiny.", "",
             f"- **{len(rows)}** assets checked",
             f"- **{len(kinds['line_art'])}** pure line art (every shape has an ink stroke): draw perfectly",
             f"- **{len(kinds['mixed'])}** mixed (ink outlines plus some fill-only shapes): fill-only parts get "
             f"an automatic outline (**{sum(r['auto_outlined'] for r in rows)}** shapes in total)",
             f"- **{len(kinds['fill_only'])}** fill-only (no strokes at all)",
             f"- **{len(redraw)}** still need redrawing (less than 60 % of the coloured area gets a drawn line)", ""]
    if redraw:
        lines += ["## Still needs redrawing", "", "| Asset | Kind | Line coverage | Fill-only shapes |", "|---|---|---|---|"]
        lines += [f"| {r['id']} | {r['kind']} | {int(r['line_coverage'] * 100)} % | {r['fill_only']} |" for r in redraw]
        lines.append("")
    else:
        lines += ["## Still needs redrawing", "", "None: every asset has a drawn line around at least 60 % of its "
                  "coloured area.", ""]
    lines += ["## All assets", "", "| Asset | Kind | Shapes | Stroked | Fill-only | Auto-outlined | Line coverage | "
              "Pen strokes |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['id']} | {r['kind']} | {r['shapes']} | {r['stroked']} | {r['fill_only']} | "
                     f"{r['auto_outlined']} | {int(r['line_coverage'] * 100)} % | {r['strokes']} |")
    Path(a.out).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(rows)} assets: {len(kinds['line_art'])} line art, {len(kinds['mixed'])} mixed, "
          f"{len(kinds['fill_only'])} fill-only, {len(redraw)} need redrawing -> {a.out}")
    for r in redraw:
        print("  redraw:", r["id"], f"{int(r['line_coverage'] * 100)} %")
    return 0


if __name__ == "__main__":
    sys.exit(main())
